import { test, expect } from '@playwright/test';

test('road checkout snapshots flow through automatic optimization, admin map and courier assignment', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const response = await page.goto('/admin/login');
  expect(response?.headers()['x-shipx-qa']).toBe('isolated-checkout');
  await page.getByLabel('Email', { exact: true }).fill('trips-admin-ui@example.test');
  await page.getByLabel('Kata sandi', { exact: true }).fill('ShipX-QA-Admin-2026!');
  await page.getByRole('button', { name: 'Masuk', exact: true }).click();
  await expect(page).toHaveURL(/\/admin$/);
  await page.goto('/admin/depot');
  await expect(page.getByText('Valhalla lokal aktif', { exact: true })).toBeVisible();
  await page.goto('/admin/trips/create');
  const initial = JSON.parse((await page.locator('#app').getAttribute('data-page'))!).props;
  const orders = initial.orders.filter((order: { address_text: string }) => order.address_text === 'Alamat QA khusus trip');
  expect(orders).toHaveLength(2);
  expect(orders.map((order: { delivery_type: string }) => order.delivery_type).sort()).toEqual(['express', 'regular']);
  await page.goto(`/admin/orders/${orders[0].id}`);
  const snapshot = JSON.parse((await page.locator('#app').getAttribute('data-page'))!).props.order;
  expect(snapshot.delivery_estimate.provider).toBe('valhalla-local');
  expect(snapshot.delivery_estimate.travel_seconds).toBeGreaterThan(0);
  expect(snapshot.delivery_distance_m).toBeGreaterThan(0);
  await page.goto('/admin/trips/create');
  const group = initial.deliveryGroups.find((candidate: {delivery_slot_id: number}) => candidate.delivery_slot_id === orders[0].delivery_slot_id);
  await page.getByLabel('Jadwal pengantaran', { exact: true }).selectOption(group.key);
  await page.getByLabel('Kurir', { exact: true }).selectOption({ label: 'QA Kurir' });
  await page.getByLabel('Kendaraan', { exact: true }).selectOption({ label: 'QA-TRIP · B2026QA' });
  await page.locator('#departure_local').fill('09:00');
  for (const order of orders) await page.getByRole('checkbox', { name: new RegExp(order.order_number) }).check();
  await page.getByRole('button', { name: 'Simpan draft', exact: true }).click();
  await expect(page).toHaveURL(/\/admin\/trips\/\d+$/);
  const tripId = page.url().split('/').pop();
  await expect(page.getByLabel('Ambil waktu jalan otomatis dari Valhalla')).toBeChecked();
  const previewResponse = page.waitForResponse(response => response.url().endsWith('/optimization/preview'));
  await page.getByRole('button', { name: 'Hitung rekomendasi rute', exact: true }).click();
  const preview = await previewResponse;
  expect(preview.status()).toBe(200);
  expect((await preview.json()).data.road_source.provider).toBe('valhalla-local');
  await page.getByRole('button', { name: 'Terapkan rekomendasi', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Rute hasil optimasi diterapkan');
  await page.reload();
  const mapResponse = page.waitForResponse(response => response.url().endsWith('/route-preview'));
  await page.getByRole('button', { name: 'Hitung peta rute', exact: true }).click();
  const map = await mapResponse;
  expect(map.status()).toBe(200);
  expect((await map.json()).data.shapes).toHaveLength(3);
  await expect(page.getByLabel('Peta rencana trip')).toBeVisible();
  await expect(page.locator('.shipx-route-number').first()).toHaveCSS('background-color', 'rgb(0, 98, 65)');
  await expect(page.getByText(/^Urutan awal /)).toBeVisible();
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByLabel('Peta rencana trip').scrollIntoViewIfNeeded();
    await page.screenshot({ path: `test-results/road-planning-${width}.png` });
  }
  await page.getByRole('button', { name: 'Tetapkan trip', exact: true }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: 'Tetapkan trip', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Buka ulang trip', exact: true })).toBeVisible();
  await expect(page.getByLabel('Sumber estimasi jalan', { exact: true })).toHaveValue(/Valhalla lokal/);
  const login = await page.request.post('/api/v1/auth/login', { data: { email: 'courier-ui@example.test', password: 'ShipX-QA-Courier-2026!', device_name: 'Road QA' } });
  const headers = { Authorization: `Bearer ${(await login.json()).data.token}` };
  const courier = await page.request.get(`/api/v1/courier/trips/${tripId}`, { headers });
  expect(courier.status()).toBe(200);
  expect((await courier.json()).data.stops.map((stop: { delivery_type: string }) => stop.delivery_type).sort()).toEqual(['express', 'regular']);
  expect(errors).toEqual([]);
});

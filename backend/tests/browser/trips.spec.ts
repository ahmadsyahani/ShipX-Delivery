import { test, expect, type Page } from '@playwright/test';

async function login(page: Page) {
  const response = await page.goto('/admin/login');
  expect(response?.headers()['x-shipx-qa']).toBe('isolated-checkout');
  await page.getByLabel('Email', {exact:true}).fill('trips-admin-ui@example.test');
  await page.getByLabel('Kata sandi', {exact:true}).fill('ShipX-QA-Admin-2026!');
  await page.getByRole('button', {name:'Masuk',exact:true}).click();
  await expect(page).toHaveURL(/\/admin$/);
}

test('manual trip: order sequence, assignment, courier privacy, reopen and cancellation', async ({page,context}) => {
  const errors:string[]=[];
  page.on('pageerror', e=>errors.push(e.message));
  await login(page);
  await page.goto('/admin/trips/create');
  await expect(page.getByRole('button',{name:'Simpan draft',exact:true})).toBeDisabled();
  const props=await page.locator('#app').getAttribute('data-page');
  const initial=JSON.parse(props!).props;
  const candidates=initial.orders.filter((o:{address_text:string})=>o.address_text==='Alamat QA khusus trip');
  expect(candidates).toHaveLength(2);
  const group=initial.deliveryGroups.find((g:{delivery_slot_id:number})=>g.delivery_slot_id===candidates[0].delivery_slot_id);
  await page.getByLabel('Jadwal pengantaran',{exact:true}).selectOption(group.key);
  const departure=new Date(new Date(candidates[0].window_start_at).getTime()-3600000);
  const parts=Object.fromEntries(new Intl.DateTimeFormat('en-GB',{timeZone:initial.timezone,year:'numeric',month:'2-digit',day:'2-digit',hour:'2-digit',minute:'2-digit',hour12:false}).formatToParts(departure).map(p=>[p.type,p.value]));
  await page.getByLabel('Kurir',{exact:true}).selectOption({label:'QA Kurir'});
  await page.getByLabel('Kendaraan',{exact:true}).selectOption({label:'QA-TRIP · B2026QA'});
  await page.locator('#departure_local').fill(`${parts.hour}:${parts.minute}`);
  for(const o of candidates) await page.getByRole('checkbox',{name:new RegExp(o.order_number)}).check();
  await expect(page.getByRole('status')).toContainText('Beban terpakai: 40%');
  await page.getByRole('button',{name:'Turunkan tujuan 1'}).click();
  await page.screenshot({path:'test-results/trip-form-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Simpan draft',exact:true}).click();
  await expect(page).toHaveURL(/\/admin\/trips\/\d+$/);
  const url=page.url(), id=url.split('/').pop();
  const stale=await context.newPage();await stale.goto(url);
  await page.getByRole('button',{name:'Tetapkan trip',exact:true}).click();
  await page.getByRole('alertdialog').getByRole('button',{name:'Tetapkan trip',exact:true}).click();
  await expect(page.getByRole('button',{name:'Buka ulang trip',exact:true})).toBeVisible();
  const auth=await page.request.post('/api/v1/auth/login',{data:{email:'courier-ui@example.test',password:'ShipX-QA-Courier-2026!',device_name:'Trip QA'}});
  expect(auth.status()).toBe(200);
  const identity=(await auth.json()).data;
  const headers={Authorization:`Bearer ${identity.token}`,Accept:'application/json'};
  const assigned=await page.request.get(`/api/v1/courier/trips/${id}`,{headers});
  expect(assigned.status()).toBe(200);
  const detail=(await assigned.json()).data;
  expect(detail.stops.map((s:{order_id:string})=>s.order_id)).toEqual([...candidates].reverse().map((o:{id:number})=>String(o.id)));
  expect(detail.estimated_arrival_at).toBeNull();
  await stale.getByRole('button',{name:'Tetapkan trip',exact:true}).click();
  await stale.getByRole('alertdialog').getByRole('button',{name:'Tetapkan trip',exact:true}).click();
  await expect(stale.getByRole('heading',{name:'Perubahan belum disimpan'})).toBeVisible();await stale.close();
  await page.screenshot({path:'test-results/trip-assigned-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/trip-detail-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Buka ulang trip',exact:true}).click();
  await page.getByLabel('Alasan',{exact:true}).fill('Tinjau ulang urutan tujuan');
  await page.getByRole('alertdialog').getByRole('button',{name:'Buka ulang trip',exact:true}).click();
  await expect(page.getByRole('link',{name:'Edit rencana'})).toBeVisible();
  expect((await page.request.get(`/api/v1/courier/trips/${id}`,{headers})).status()).toBe(404);
  await page.getByRole('link',{name:'Edit rencana'}).click();
  await expect(page.getByRole('heading',{name:'Edit rencana trip'})).toBeVisible();
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/trip-form-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Simpan draft',exact:true}).click();
  await page.getByRole('button',{name:'Batalkan trip',exact:true}).click();
  await page.getByLabel('Alasan',{exact:true}).fill('Selesai QA penugasan');
  await page.getByRole('alertdialog').getByRole('button',{name:'Batalkan trip',exact:true}).click();
  await expect(page.getByText('Dibatalkan · Rute versi')).toBeVisible();
  expect(errors).toEqual([]);
});

import { test, expect } from '@playwright/test';

test('admin previews, applies and assigns an optimized route with road review prefill', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const response = await page.goto('/admin/login');
  expect(response?.headers()['x-shipx-qa']).toBe('isolated-checkout');
  await page.getByLabel('Email', { exact: true }).fill('trips-admin-ui@example.test');
  await page.getByLabel('Kata sandi', { exact: true }).fill('ShipX-QA-Admin-2026!');
  await page.getByRole('button', { name: 'Masuk', exact: true }).click();
  await expect(page).toHaveURL(/\/admin$/);
  await page.goto('/admin/trips/create');
  const initial = JSON.parse((await page.locator('#app').getAttribute('data-page'))!).props;
  const orders = initial.orders.filter((order: { address_text: string }) => order.address_text === 'Alamat QA khusus trip');
  expect(orders).toHaveLength(2);
  const group = initial.deliveryGroups.find((candidate: {delivery_slot_id: number}) => candidate.delivery_slot_id === orders[0].delivery_slot_id);
  await page.getByLabel('Jadwal pengantaran', {exact: true}).selectOption(group.key);
  await expect(page.getByLabel('Tanggal berangkat kurir', {exact: true})).toHaveValue(group.service_date);
  await expect(page.getByLabel('Tanggal berangkat kurir', {exact: true})).toHaveAttribute('readonly', '');
  await page.screenshot({path: 'test-results/trip-group-form-desktop.png', fullPage: true});
  const departure = new Date(new Date(orders[0].window_start_at).getTime() - 3600000);
  const parts = Object.fromEntries(new Intl.DateTimeFormat('en-GB', { timeZone: initial.timezone, year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', hour12: false }).formatToParts(departure).map(part => [part.type, part.value]));
  await page.getByLabel('Kurir', { exact: true }).selectOption({ label: 'QA Kurir' });
  await page.getByLabel('Kendaraan', { exact: true }).selectOption({ label: 'QA-TRIP · B2026QA' });
  await page.locator('#departure_local').fill(`${parts.hour}:${parts.minute}`);
  for (const order of orders) await page.getByRole('checkbox', { name: new RegExp(order.order_number) }).check();
  await page.getByRole('button', { name: 'Simpan draft', exact: true }).click();
  await expect(page).toHaveURL(/\/admin\/trips\/\d+$/);
  const tripUrl = page.url();
  const tripId = tripUrl.split('/').pop();
  await page.getByLabel('Sumber waktu jalan', { exact: true }).fill('Peta jalan QA, motor, seluruh arah diperiksa');
  await page.getByText('Tempel tabel dari spreadsheet', { exact: true }).click();
  await page.getByLabel('Tabel waktu jalan dalam menit', { exact: true }).fill('0\t10\t1\n1\t0\t10\n10\t1\t0');
  await page.getByRole('button', { name: 'Gunakan tabel', exact: true }).click();
  const previewResponse = page.waitForResponse(response => response.url().endsWith('/optimization/preview') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Hitung rekomendasi rute', exact: true }).click();
  const previewResult = (await (await previewResponse).json()).data;
  expect(previewResult.departure_recommended).toBe(true);
  await expect(page.getByRole('button', { name: 'Terapkan rekomendasi', exact: true })).toBeVisible();
  await expect(page.getByText('3 menit jalan', { exact: false })).toBeVisible();
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: `test-results/trip-optimization-${width}.png`, fullPage: true });
  }
  await page.getByRole('button', { name: 'Terapkan rekomendasi', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Rute hasil optimasi diterapkan');
  await page.reload();
  await expect(page.getByText('Optimasi urutan pengantaran', { exact: true })).toBeVisible();
  const current = JSON.parse((await page.locator('#app').getAttribute('data-page'))!).props.trip;
  expect(current.selected_route.input_snapshot.orders.map((order: { id: string }) => order.id)).toEqual(orders.map((order: { id: number }) => String(order.id)).reverse());
  expect(current.selected_route.input_snapshot.optimization.leg_seconds).toEqual([60, 60, 60]);
  expect(current.planned_departure_at).toBe(previewResult.departure_at);
  await expect(page.getByLabel('Sumber waktu jalan', { exact: true })).toHaveValue('Peta jalan QA, motor, seluruh arah diperiksa');
  await page.getByRole('button', { name: 'Tetapkan trip', exact: true }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: 'Tetapkan trip', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Buka ulang trip', exact: true })).toBeVisible();
  for (const index of [0, 1, 2]) await expect(page.locator(`#leg-${index}`)).toHaveValue('1');
  await expect(page.getByLabel('Sumber estimasi jalan', { exact: true })).toHaveValue('Peta jalan QA, motor, seluruh arah diperiksa');
  const auth = await page.request.post('/api/v1/auth/login', { data: { email: 'courier-ui@example.test', password: 'ShipX-QA-Courier-2026!', device_name: 'Optimizer QA' } });
  expect(auth.status()).toBe(200);
  const headers = { Authorization: `Bearer ${(await auth.json()).data.token}`, Accept: 'application/json' };
  const courier = await page.request.get(`/api/v1/courier/trips/${tripId}`, { headers });
  expect(courier.status()).toBe(200);
  expect((await courier.json()).data.stops.map((stop: { order_id: string }) => stop.order_id)).toEqual(current.selected_route.input_snapshot.orders.map((order: { id: string }) => order.id));
  await page.getByRole('button', {name: 'Batalkan trip', exact: true}).click();
  await page.getByLabel('Alasan', {exact: true}).fill('Selesai pengujian rekomendasi jadwal');
  await page.getByRole('alertdialog').getByRole('button', {name: 'Batalkan trip', exact: true}).click();
  await expect(page.getByText('Dibatalkan · Rute versi', {exact: false})).toBeVisible();
  expect(errors).toEqual([]);
});
